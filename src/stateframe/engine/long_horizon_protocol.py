def load_validated_tasks(
    task_root: str | Path, *, family: str = TASK_FAMILY
) -> list[dict[str, Any]]:
    """Load exactly the six public ``long_horizon1`` task manifests.

    The function reads only ``public_manifest.json`` and its declared brief.
    It never walks a task's private/oracle directories and it returns the
    public source map that a worker spec needs.
    """
    family_dir = _family_dir(Path(task_root), family)
    if not family_dir.is_dir() or family_dir.is_symlink():
        raise ProtocolError(f"task family is unavailable: {family_dir}")

    staged = family == STAGED_FAMILY
    tasks: list[dict[str, Any]] = []
    for task_id in family_task_ids(task_root, family):
        task_dir = family_dir / task_id
        if not task_dir.is_dir() or task_dir.is_symlink():
            raise ProtocolError(f"validated task is unavailable: {task_id}")
        manifest_path = task_dir / "public_manifest.json"
        manifest = _json_object(manifest_path)
        if manifest.get("task_id") != task_id:
            raise ProtocolError(f"manifest task id mismatch: {task_id}")
        if not staged and manifest.get("rung") != "LONG-HORIZON-1":
            raise ProtocolError(f"task is not in the validated rung: {task_id}")
        brief_name = manifest.get("brief", "brief.md")
        brief_name = _safe_relative(brief_name, field="brief")
        brief_path = task_dir / brief_name
        if brief_path.is_symlink() or not brief_path.is_file():
            raise ProtocolError(f"missing public brief: {task_id}")
        brief = brief_path.read_text(encoding="utf-8")
        phases = None
        if staged:
            phases = _staged_phases(task_id, manifest, task_dir)
            if phases[0]["brief_path"] != brief_name:
                raise ProtocolError(f"{task_id} phase 1 brief must be the task brief")
            raw_entry = manifest.get("entry")
            if (not isinstance(raw_entry, Mapping) or not isinstance(raw_entry.get("path"), str)
                    or not isinstance(raw_entry.get("fn"), str) or not raw_entry["fn"]):
                raise ProtocolError(f"{task_id} staged manifest needs entry.path/fn")
            entry = (_safe_relative(raw_entry["path"], field="entry"), raw_entry["fn"])
            task_digest = _staged_digest(manifest_path, brief_path, phases)
        else:
            entry = ENTRYPOINTS[task_id]
            task_digest = _sha256_task(manifest_path, brief_path)
        record = {
            "task_id": task_id,
            "family": family,
            "task_digest": task_digest,
            "manifest_sha256": _sha256_bytes(manifest_path.read_bytes()),
            "brief_sha256": _sha256_bytes(brief_path.read_bytes()),
            "brief_path": brief_name,
            "entry": {"path": entry[0], "fn": entry[1]},
            "public_row": _public_row(
                task_id=task_id, manifest=manifest, brief=brief,
                task_digest=task_digest, entry=entry, phases=phases,
            ),
        }
        if phases is not None:
            record["phases"] = [
                {"phase": phase["phase"], "brief_path": phase["brief_path"],
                 "brief_sha256": phase["brief_sha256"],
                 "public_check_paths": phase["public_check_paths"]}
                for phase in phases
            ]
        tasks.append(record)
    return tasks


