def build_protocol(
    *,
    task_root: str | Path,
    release: str,
    seeds: Sequence[int] = (924103, 924104),
    batch_start: int = 305,
    slot_count: int = 4,
    usable_input_tokens: int,
    output_reserve_tokens: int,
    capacity_source: str,
    release_root: str = "/work/gate-fix/local-swarm-poc/capability-study/runtime-releases",
    model: str = "minicpm5-2b-q8",
    server_build: str = "UNVERIFIED_UNTIL_LIVE_SLOTS",
    tokenizer: str = "UNVERIFIED_UNTIL_LIVE_SLOTS",
    chat_template: str = "UNVERIFIED_UNTIL_LIVE_SLOTS",
    cache_policy: str = "enabled",
    decisions: int | None = None,
    wall_seconds: int = 14_400,
    output_per_call: int = 24_000,
    context_window_tokens: int | None = None,
    slot_profile: str = "infer-a",
    family: str = TASK_FAMILY,
    purpose: str = "calibration",
    calibration: Mapping[str, Any] | None = None,
) -> dict[str, Any]:
    """Create a reproducible protocol description without launching it.

    ``purpose="calibration"`` (the default) is a depth/mechanism measurement
    that never counts toward claims.  ``purpose="comparison"`` requires
    ``calibration={"protocol": <calibration protocol>, "receipt": <passing
    mechanism-gate report>}`` for the same release, tasks, arms and capacity.
    """
    if purpose not in PURPOSES:
        raise ProtocolError(f"purpose must be one of {sorted(PURPOSES)}")
    if purpose == "comparison" and calibration is None:
        raise ProtocolError("a comparison protocol requires a passing calibration receipt")
    if purpose == "calibration" and calibration is not None:
        raise ProtocolError("a calibration protocol cannot bind another calibration")
    if family not in FAMILY_DEFAULT_DECISIONS:
        raise ProtocolError(f"unknown task family: {family}")
    if decisions is None:
        decisions = FAMILY_DEFAULT_DECISIONS[family]
    if not isinstance(release, str) or not _RELEASE_RE.fullmatch(release):
        raise ProtocolError("release must be a non-zero 64-character lowercase SHA-256")
    if not isinstance(capacity_source, str) or not capacity_source.strip():
        raise ProtocolError("capacity_source is required; no default context is allowed")
    if capacity_source.strip().lower() in {"default", "unknown", "unspecified"}:
        raise ProtocolError("capacity_source may not be a default or unknown value")
    usable = _integer(usable_input_tokens, name="usable_input_tokens", positive=True)
    reserve = _integer(output_reserve_tokens, name="output_reserve_tokens", positive=True)
    if context_window_tokens is None:
        context_window = usable + reserve
    else:
        context_window = _integer(
            context_window_tokens, name="context_window_tokens", positive=True
        )
    if context_window < usable + reserve:
        raise ProtocolError("context_window_tokens must cover input plus output reserve")
    if not isinstance(slot_profile, str) or not slot_profile.strip():
        raise ProtocolError("slot_profile is required")
    _integer(batch_start, name="batch_start", positive=True)
    slots = _integer(slot_count, name="slot_count", positive=True)
    if slots < len(COMPARISON_ARM_IDS):
        raise ProtocolError("slot_count must cover all four comparison arms")
    _integer(decisions, name="decisions", positive=True)
    _integer(wall_seconds, name="wall_seconds", positive=True)
    _integer(output_per_call, name="output_per_call", positive=True)

    normalized_seeds = tuple(_integer(seed, name="seed", positive=True) for seed in seeds)
    if not normalized_seeds or len(set(normalized_seeds)) != len(normalized_seeds):
        raise ProtocolError("seeds must be a non-empty unique sequence")

    tasks = load_validated_tasks(task_root, family=family)
    definitions = _arm_definitions(family)
    all_batches = {arm_id: batch_start + index for index, arm_id in enumerate(ARM_ORDER)}
    runs: list[dict[str, Any]] = []
    for task_index, task in enumerate(tasks):
        for seed_index, seed in enumerate(normalized_seeds):
            pair_index = task_index * len(normalized_seeds) + seed_index
            wave = pair_index // slots
            for arm_index, arm_id in enumerate(ARM_ORDER):
                definition = definitions[arm_id]
                label = run_label(task['task_id'], seed, arm_id)
                runs.append(
                    {
                        "label": label,
                        "task_id": task["task_id"],
                        "seed": seed,
                        "arm": arm_id,
                        "batch": all_batches[arm_id],
                        "slot": (pair_index + arm_index) % slots,
                        "wave": wave,
                        "pair_index": pair_index,
                    }
                )

    task_records = [
        {
            key: task[key]
            for key in (
                "task_id",
                "family",
                "task_digest",
                "manifest_sha256",
                "brief_sha256",
                "brief_path",
                "entry",
            )
        }
        for task in tasks
    ]
    for record, task in zip(task_records, tasks):
        if "phases" in task:
            record["phases"] = task["phases"]
    protocol: dict[str, Any] = {
        "protocol_version": PROTOCOL_VERSION,
        "enabled_switch": PROTOCOL_SWITCH,
        "telemetry_switch": TELEMETRY_SWITCH,
        "decode_depth_switch": DECODE_DEPTH_SWITCH,
        "scope": (f"{len(tasks)} validated {family} public tasks; four comparison arms, "
                  "one matched-policy ablation, one overflow control"),
        "purpose": purpose,
        "task_family": family,
        "staged_phases": family == STAGED_FAMILY,
        "claim_scope": dict(CLAIM_SCOPE),
        "summary_policy": summary_policy_fingerprint(),
        "mechanism_gate": mechanism_gate_contract(),
        "preregistration": preregistration(purpose),
        "tasks": task_records,
        "seeds": list(normalized_seeds),
        "comparison_arms": list(COMPARISON_ARM_IDS),
        "ablation_arm": ABLATION_ARM_ID,
        "control_arm": CONTROL_ARM_ID,
        "arms": list(ARM_ORDER),
        "arm_definitions": definitions,
        "batches": all_batches,
        "context": {
            "usable_input_tokens": usable,
            "output_reserve_tokens": reserve,
            "context_window_tokens": context_window,
            "slot_profile": slot_profile,
            "slot_count": slots,
            "capacity_source": capacity_source,
            "capacity_must_be_live_slot_metadata": True,
            "depth_threshold_fraction": DEPTH_MIN_FRACTION,
        },
        "budgets": {
            "decisions": decisions,
            "wall_seconds": wall_seconds,
            "output_per_call": output_per_call,
            "summary_output_tokens": min(4_096, output_per_call),
            "reasoning_budget_tokens": -1,
        },
        "runtime": {
            "release_sha256": release,
            "release_root": release_root,
            "model": model,
            "server_build": server_build,
            "tokenizer": tokenizer,
            "chat_template": chat_template,
            "cache_policy": cache_policy,
            "tool_surface": "native_tools_v1",
            "sampling": dict(_DEFAULT_SAMPLING),
            "common_environment": _common_runtime_profile(),
        },
        "capacity_preflight": {
            "schema": "study-capacity/1",
            "context_limit": context_window,
            "slot_profile": slot_profile,
            "requires_explicit_slot": True,
        },
        "grading": {
            "adapter": "grade_realistic.py",
            "pool_wrapper": "grade_long_horizon.py",
            "terminal_only": True,
            "correctness_requires_public_and_hidden": True,
        },
        "depth_strata": [
            {"name": "0.5-0.85B", "logical_fraction": [0.5, 0.85]},
            {"name": "0.85-1.5B", "logical_fraction": [0.85, 1.5]},
            {"name": "2-4B", "logical_fraction": [2.0, 4.0]},
        ],
        "overflow_policy": {
            "control_arm": CONTROL_ARM_ID,
            "terminal_result": "CONTEXT_OVERFLOW",
            "counts_as_failure": True,
            "remains_in_assigned_cohort_denominator": True,
            "never_treat_as_harness_exclusion": True,
        },
        "runs": runs,
    }
    if calibration is not None:
        protocol["calibration"] = bind_calibration(
            calibration, candidate=protocol)
    protocol["depth_strata"] = [
        {"name": "0.5-0.85B", "logical_fraction": [0.5, 0.85],
         "depth_source": CUMULATIVE_DEPTH_SOURCE},
        {"name": "0.85-1.5B", "logical_fraction": [0.85, 1.5],
         "depth_source": CUMULATIVE_DEPTH_SOURCE},
        {"name": "2-4B", "logical_fraction": [2.0, 4.0],
         "depth_source": CUMULATIVE_DEPTH_SOURCE},
    ]
    protocol["protocol_sha256"] = protocol_digest(protocol)
    return protocol


_CALIBRATION_MUST_MATCH = ("task_family", "tasks", "arm_definitions", "summary_policy",
                           "mechanism_gate", "budgets", "capacity_preflight")


def bind_calibration(calibration: Mapping[str, Any], *, candidate: Mapping[str, Any]
                     ) -> dict[str, Any]:
    """Bind a comparison to a passing calibration of the SAME configuration."""
    cal = calibration.get("protocol")
    receipt = calibration.get("receipt")
    if not isinstance(cal, Mapping) or not isinstance(receipt, Mapping):
        raise ProtocolError("calibration needs its protocol and mechanism-gate receipt")
    if cal.get("purpose") != "calibration" or cal.get("protocol_sha256") != protocol_digest(cal):
        raise ProtocolError("calibration protocol is not an intact calibration protocol")
    if receipt.get("schema") != "long-horizon-mechanism-gate-report/1" or receipt.get("ok") is not True:
        raise ProtocolError("calibration mechanism gate did not pass")
    if receipt.get("protocol_sha256") != cal.get("protocol_sha256"):
        raise ProtocolError("calibration receipt belongs to another protocol")
    if receipt.get("contract") != mechanism_gate_contract():
        raise ProtocolError("calibration receipt used a different mechanism contract")
    expected = {run["label"] for run in cal.get("runs", ())
                if isinstance(run, Mapping) and run.get("arm") != CONTROL_ARM_ID}
    cells = receipt.get("cells")
    judged = {cell.get("label") for cell in cells if isinstance(cell, Mapping)
              and cell.get("passed") is True} if isinstance(cells, list) else set()
    if not expected or judged != expected:
        raise ProtocolError("calibration receipt does not pass every assigned cell")
    for field in _CALIBRATION_MUST_MATCH:
        if cal.get(field) != candidate.get(field):
            raise ProtocolError(f"calibration differs from the comparison in {field}")
    for field in ("release_sha256", "model", "tokenizer", "chat_template", "server_build"):
        if (cal.get("runtime") or {}).get(field) != (candidate.get("runtime") or {}).get(field):
            raise ProtocolError(f"calibration ran a different runtime {field}")
    for field in ("usable_input_tokens", "output_reserve_tokens", "context_window_tokens",
                  "slot_profile"):
        if (cal.get("context") or {}).get(field) != (candidate.get("context") or {}).get(field):
            raise ProtocolError(f"calibration used a different capacity {field}")
    if set(cal.get("seeds") or ()) & set(candidate.get("seeds") or ()):
        raise ProtocolError("comparison seeds must not reuse calibration seeds")
    receipt_sha = hashlib.sha256(json.dumps(receipt, sort_keys=True, separators=(",", ":"))
                                 .encode("utf-8")).hexdigest()
    return {
        "calibration_protocol_sha256": cal["protocol_sha256"],
        "receipt_sha256": receipt_sha,
        "deep_stratum_eligibility": dict(receipt.get("deep_stratum_eligibility") or {}),
        "counts_toward_claims": False,
    }


def protocol_digest(protocol: Mapping[str, Any]) -> str:
    """Hash protocol content without making the digest self-referential."""
    payload = {key: value for key, value in protocol.items() if key != "protocol_sha256"}
    encoded = json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return _sha256_bytes(encoded)


def protocol_switch_env(base: Mapping[str, str], *, enabled: bool) -> dict[str, str]:
    """Apply the opt-in protocol switch without changing the disabled path."""
    result = dict(base)
    if enabled:
        result[PROTOCOL_SWITCH] = "on"
        result[TELEMETRY_SWITCH] = "on"
        result[DECODE_DEPTH_SWITCH] = "on"
    return result


def _task_ids(protocol: Mapping[str, Any]) -> list[str]:
    tasks = protocol.get("tasks")
    if not isinstance(tasks, list):
        return []
    return [
        item["task_id"]
        for item in tasks
        if isinstance(item, Mapping) and isinstance(item.get("task_id"), str)
    ]


def check_protocol(
    protocol: Mapping[str, Any],
    *,
    task_root: str | Path | None = None,
    runtime_capabilities: Iterable[str] | None = None,
    require_runtime_capabilities: bool = False,
    require_live_capacity: bool = True,
) -> dict[str, Any]:
    """Run non-launching structural, task, capacity, and capability checks."""
    errors: list[str] = []
    warnings: list[str] = []
    if protocol.get("protocol_version") != PROTOCOL_VERSION:
        errors.append("unsupported protocol_version")
    if tuple(protocol.get("comparison_arms", ())) != COMPARISON_ARM_IDS:
        errors.append("comparison arm order does not match the four-arm contract")
    if protocol.get("control_arm") != CONTROL_ARM_ID:
        errors.append("missing uncompacted overflow control arm")
    if protocol.get("ablation_arm") != ABLATION_ARM_ID:
        errors.append("missing matched-policy history ablation arm")
    if tuple(protocol.get("arms", ())) != ARM_ORDER:
        errors.append("arm list must contain four comparison arms, the ablation, and the control")
    if protocol.get("protocol_sha256") != protocol_digest(protocol):
        errors.append("protocol_sha256 does not match protocol content")
    family = protocol.get("task_family", TASK_FAMILY)
    if family not in FAMILY_DEFAULT_DECISIONS:
        errors.append(f"unknown task family: {family}")
        family = TASK_FAMILY
    if protocol.get("purpose") not in PURPOSES:
        errors.append("protocol purpose must be calibration or comparison")
    if protocol.get("purpose") == "comparison":
        bound = protocol.get("calibration")
        if (not isinstance(bound, Mapping)
                or not isinstance(bound.get("receipt_sha256"), str)
                or not isinstance(bound.get("calibration_protocol_sha256"), str)
                or not isinstance(bound.get("deep_stratum_eligibility"), Mapping)):
            errors.append("comparison protocol is not bound to a passing calibration receipt")
    if protocol.get("mechanism_gate") != mechanism_gate_contract():
        errors.append("mechanism gate contract differs from the canonical floors")
    if protocol.get("claim_scope") != CLAIM_SCOPE:
        errors.append("claim scope differs from the canonical package/attribution scope")
    live_summary_policy = summary_policy_fingerprint()
    recorded_summary_policy = protocol.get("summary_policy")
    if not isinstance(recorded_summary_policy, Mapping) or not recorded_summary_policy.get("available"):
        errors.append("strong-history summary policy was not frozen into the protocol")
    elif live_summary_policy.get("available") and dict(recorded_summary_policy) != live_summary_policy:
        errors.append("strong-history summary policy changed since the protocol was frozen")

    context = protocol.get("context")
    if not isinstance(context, Mapping):
        errors.append("context metadata is missing")
        context = {}
    usable = context.get("usable_input_tokens")
    reserve = context.get("output_reserve_tokens")
    if type(usable) is not int or usable <= 0:
        errors.append("usable_input_tokens must be positive")
    if type(reserve) is not int or reserve <= 0:
        errors.append("output_reserve_tokens must be positive")
    context_window = context.get("context_window_tokens")
    if type(context_window) is not int or context_window <= 0:
        errors.append("context_window_tokens must be positive")
    elif type(usable) is int and usable > 0 and type(reserve) is int and reserve > 0:
        if context_window < usable + reserve:
            errors.append("context_window_tokens does not cover input plus output reserve")
    slot_profile = context.get("slot_profile")
    if not isinstance(slot_profile, str) or not slot_profile.strip():
        errors.append("slot_profile is missing")
    capacity = protocol.get("capacity_preflight")
    if not isinstance(capacity, Mapping):
        errors.append("capacity_preflight metadata is missing")
    elif capacity.get("context_limit") != context_window:
        errors.append("capacity_preflight context limit does not match context metadata")
    elif capacity.get("requires_explicit_slot") is not True:
        errors.append("capacity preflight must require an explicit live slot")
    source = context.get("capacity_source")
    live_source = isinstance(source, str) and source.lower().startswith(("live:", "slot:"))
    if require_live_capacity and not live_source:
        errors.append("capacity_source is not live slot metadata")
    elif not live_source:
        warnings.append("capacity source is not live slot metadata")
    if (
        live_source
        and context.get("slot_profile") == "infer-a"
        and context_window != INFER_A_CONTEXT_TOKENS
    ):
        errors.append("infer-a live slot context must be exactly 65536 tokens")

    task_ids = _task_ids(protocol)
    if family == STAGED_FAMILY:
        expected_count = STAGED_TASK_COUNT
        if (len(task_ids) != STAGED_TASK_COUNT
                or any(not _STAGED_ID_RE.match(task_id) for task_id in task_ids)
                or task_ids != sorted(task_ids)):
            errors.append("task selection is not exactly the staged long_horizon2 family")
        for item in protocol.get("tasks") or ():
            phases = item.get("phases") if isinstance(item, Mapping) else None
            if not isinstance(phases, list) or len(phases) < 2:
                errors.append(f"staged task has no frozen phases: {item.get('task_id') if isinstance(item, Mapping) else item}")
        if protocol.get("staged_phases") is not True:
            errors.append("staged family protocol must enable staged phase release")
    else:
        expected_count = len(REQUIRED_TASK_IDS)
        if tuple(task_ids) != REQUIRED_TASK_IDS:
            errors.append("task selection is not exactly the six validated public IDs")
    task_records = protocol.get("tasks")
    if not isinstance(task_records, list) or len(task_records) != expected_count:
        errors.append("task digest records are incomplete")
    else:
        for item in task_records:
            if not isinstance(item, Mapping) or not isinstance(item.get("task_digest"), str):
                errors.append("every task must carry a task_digest")
                break

    definitions = protocol.get("arm_definitions")
    if not isinstance(definitions, Mapping):
        errors.append("arm_definitions are missing")
        definitions = {}
    canonical_definitions = _arm_definitions(family)
    runtime = protocol.get("runtime")
    if not isinstance(runtime, Mapping):
        errors.append("runtime contract is missing")
        runtime = {}
    common_environment = runtime.get("common_environment")
    if common_environment != _common_runtime_profile():
        errors.append("common runtime environment does not match the canonical profile")
    sampling = runtime.get("sampling")
    if not isinstance(sampling, Mapping):
        errors.append("sampling contract is missing")
    else:
        for field, expected in _DEFAULT_SAMPLING.items():
            try:
                actual = _finite_number(sampling.get(field), name=f"sampling.{field}")
            except ProtocolError:
                errors.append(f"sampling.{field} is not a finite number")
                continue
            if actual != expected:
                errors.append(f"sampling.{field} does not match the canonical runtime profile")
    for arm_id in ARM_ORDER:
        item = definitions.get(arm_id)
        canonical = canonical_definitions[arm_id]
        if not isinstance(item, Mapping):
            errors.append(f"arm definition missing: {arm_id}")
            continue
        for field in ("presentation_arm", "compaction", "is_control"):
            if item.get(field) != canonical[field]:
                errors.append(f"{arm_id} {field} does not match the canonical arm contract")
        required_switches = item.get("required_switches", ())
        if not isinstance(required_switches, (list, tuple)):
            errors.append(f"{arm_id} required_switches are not a sequence")
            required_switches = ()
        if tuple(required_switches) != tuple(canonical["required_switches"]):
            errors.append(f"{arm_id} required_switches do not match the canonical arm contract")
        flags = item.get("flags")
        if not isinstance(flags, Mapping):
            errors.append(f"arm flags missing: {arm_id}")
        else:
            if dict(flags) != canonical["flags"]:
                errors.append(f"{arm_id} flags do not exactly match the canonical arm contract")
            for flag, expected in canonical["flags"].items():
                if flags.get(flag) != expected:
                    errors.append(
                        f"{arm_id} flag {flag} does not match the canonical arm contract"
                    )
    overflow = protocol.get("overflow_policy")
    if not isinstance(overflow, Mapping) or overflow.get("counts_as_failure") is not True:
        errors.append("overflow control is not scored as an assigned failure")

    if task_root is not None and not errors:
        try:
            actual = load_validated_tasks(task_root, family=family)
            if [item["task_id"] for item in actual] != task_ids:
                errors.append("frozen task list differs from the task family on disk")
            actual_by_id = {item["task_id"]: item for item in actual}
            for item in task_records:
                expected = actual_by_id.get(item.get("task_id"))
                if expected is None or expected["task_digest"] != item.get("task_digest"):
                    errors.append(f"task digest mismatch: {item.get('task_id')}")
        except ProtocolError as exc:
            errors.append(str(exc))

    if runtime_capabilities is None:
        if require_runtime_capabilities:
            errors.append("runtime capability receipt is required before launch")
        else:
            warnings.append("runtime capability receipt is missing; not launch-ready")
    else:
        available = {str(value) for value in runtime_capabilities}
        for arm_id in ARM_ORDER:
            required = canonical_definitions[arm_id]["required_switches"]
            required = [PROTOCOL_SWITCH, TELEMETRY_SWITCH, DECODE_DEPTH_SWITCH,
                        *REQUIRED_RUNTIME_FEATURES, *required]
            if family == STAGED_FAMILY:
                required.append(STAGED_SWITCH)
            missing = list(dict.fromkeys(switch for switch in required if switch not in available))
            if missing:
                errors.append(f"runtime lacks {arm_id} switch(es): {','.join(missing)}")

    return {
        "ok": not errors,
        "errors": errors,
        "warnings": warnings,
        "task_count": len(task_ids),
        "comparison_arm_count": len(protocol.get("comparison_arms", ()))
        if isinstance(protocol.get("comparison_arms"), list)
        else 0,
    }


def check_depth_preflight(
    protocol: Mapping[str, Any],
    records: Iterable[Mapping[str, Any]],
    *,
    minimum_fraction: float = DEPTH_MIN_FRACTION,
) -> dict[str, Any]:
    """Require every selected task to reach strictly more than 50% of B.

    ``rendered_prompt_tokens`` is the only accepted depth measurement.  A
    logical transcript counter, byte estimate, or a summary request is not a
    substitute for the final submitted prompt.
    """
    fraction = _finite_number(minimum_fraction, name="minimum_fraction")
    if not 0.0 < fraction < 1.0:
        raise ProtocolError("minimum_fraction must be between zero and one")
    context = protocol.get("context")
    if not isinstance(context, Mapping) or type(context.get("usable_input_tokens")) is not int:
        raise ProtocolError("protocol has no usable input capacity")
    protocol_usable = int(context["usable_input_tokens"])
    if protocol_usable <= 0:
        raise ProtocolError("protocol usable input capacity must be positive")
    threshold = protocol_usable * fraction
    task_ids = _task_ids(protocol)
    maxima: dict[str, int | None] = {task_id: None for task_id in task_ids}
    eligible: dict[str, int] = {task_id: 0 for task_id in task_ids}
    rejected: dict[str, int] = {task_id: 0 for task_id in task_ids}

    summary_roles = {"summary", "compaction", "history_compaction", "frame_compaction"}
    for record in records:
        if not isinstance(record, Mapping):
            continue
        task_id = record.get("task_id", record.get("task"))
        if task_id not in maxima:
            continue
        role = str(record.get("request_role", record.get("role", "solver"))).lower()
        if role in summary_roles:
            rejected[task_id] += 1
            continue
        depth = record.get("rendered_prompt_tokens")
        source = record.get("depth_source")
        if type(depth) is not int or depth < 0 or source != "rendered_prompt_tokens":
            rejected[task_id] += 1
            continue
        row_usable = record.get("usable_input_tokens", protocol_usable)
        if type(row_usable) is not int or row_usable != protocol_usable:
            rejected[task_id] += 1
            continue
        eligible[task_id] += 1
        maxima[task_id] = depth if maxima[task_id] is None else max(maxima[task_id], depth)

    task_reports: dict[str, dict[str, Any]] = {}
    for task_id in task_ids:
        maximum = maxima[task_id]
        task_reports[task_id] = {
            "passed": maximum is not None and maximum > threshold,
            "max_rendered_prompt_tokens": maximum,
            "threshold_tokens": threshold,
            "usable_input_tokens": protocol_usable,
            "eligible_responses": eligible[task_id],
            "rejected_responses": rejected[task_id],
        }
    return {
        "ok": bool(task_reports) and all(item["passed"] for item in task_reports.values()),
        "minimum_fraction": fraction,
        "usable_input_tokens": protocol_usable,
        "tasks": task_reports,
    }
