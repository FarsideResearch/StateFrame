def task_slug(task_id: str) -> str:
    """Letters/underscore-only slug (pool label grammar) for either family."""
    if task_id in TASK_SLUGS:
        return TASK_SLUGS[task_id]
    match = _STAGED_ID_RE.match(str(task_id))
    if match is None:
        raise ProtocolError(f"task has no pool label slug: {task_id}")
    return STAGED_SLUG_PREFIX + "abcdefghi"[int(match.group(1)) - 1]


_BAD_PUBLIC_PATH_PARTS = {
    "private",
    "hidden_tests",
    "near_miss",
    "gold",
    "oracle",
}
_RELEASE_RE = re.compile(r"^[0-9a-f]{64}$")


class ProtocolError(ValueError):
    """Raised when a protocol would be unsafe or not reproducible."""


def _integer(value: object, *, name: str, positive: bool = False) -> int:
    if type(value) is not int or (positive and value <= 0) or (not positive and value < 0):
        expectation = "a positive integer" if positive else "a non-negative integer"
        raise ProtocolError(f"{name} must be {expectation}")
    return value


def _finite_number(value: object, *, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (int, float)):
        raise ProtocolError(f"{name} must be finite")
    number = float(value)
    if not math.isfinite(number):
        raise ProtocolError(f"{name} must be finite")
    return number


def _safe_relative(value: object, *, field: str = "path") -> str:
    if not isinstance(value, str) or not value or "\x00" in value or "\\" in value:
        raise ProtocolError(f"{field} must be a relative POSIX path")
    path = PurePosixPath(value)
    if path.is_absolute() or ".." in path.parts or str(path) != value or value == ".":
        raise ProtocolError(f"{field} must be a relative POSIX path")
    if any(part.lower() in _BAD_PUBLIC_PATH_PARTS for part in path.parts):
        raise ProtocolError(f"{field} names controller-only material")
    return value


def _json_object(path: Path) -> dict[str, Any]:
    if path.is_symlink() or not path.is_file():
        raise ProtocolError(f"missing or linked public file: {path.name}")
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, TypeError, ValueError) as exc:
        raise ProtocolError(f"invalid JSON: {path}") from exc
    if not isinstance(value, dict):
        raise ProtocolError(f"expected a JSON object: {path}")
    return value


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _sha256_task(manifest: Path, brief: Path) -> str:
    return _sha256_bytes(
        manifest.read_bytes() + b"\x00long-horizon-brief\x00" + brief.read_bytes()
    )


def _family_dir(task_root: Path, family: str) -> Path:
    root = task_root.resolve()
    return root if root.name == family else root / family


def _public_files(manifest: Mapping[str, Any]) -> dict[str, dict[str, str]]:
    raw_files = manifest.get("files")
    if isinstance(raw_files, Mapping):
        items = raw_files.items()
    elif isinstance(raw_files, list):
        items = (
            (item.get("path"), item)
            for item in raw_files
            if isinstance(item, Mapping)
        )
    else:
        raise ProtocolError("public manifest has no files list")

    result: dict[str, dict[str, str]] = {}
    for relative, payload in items:
        relative = _safe_relative(relative, field="public file")
        if not isinstance(payload, Mapping):
            raise ProtocolError(f"public file entry is not an object: {relative}")
        source = payload.get("source", payload.get("parent_src"))
        if not isinstance(source, str):
            raise ProtocolError(f"public file has no source: {relative}")
        result[relative] = {"parent_src": source}
    if not result:
        raise ProtocolError("public manifest has no public files")
    return result


def _public_tests(manifest: Mapping[str, Any]) -> list[dict[str, str]]:
    raw_tests = manifest.get("public_tests")
    if not isinstance(raw_tests, list) or not raw_tests:
        raise ProtocolError("public manifest has no public_tests")
    tests: list[dict[str, str]] = []
    for item in raw_tests:
        if not isinstance(item, Mapping):
            raise ProtocolError("public test entry is not an object")
        path = _safe_relative(item.get("path"), field="public test")
        source = item.get("source")
        if not isinstance(source, str):
            raise ProtocolError(f"public test has no source: {path}")
        tests.append({"path": path, "source": source})
    return tests


def _staged_phases(
    task_id: str, manifest: Mapping[str, Any], task_dir: Path
) -> list[dict[str, Any]]:
    """Split a staged manifest into ordered phases (public material only).

    Phase 1 is the initial ticket; phases 2..n are withheld by the runtime
    until the previous phase's public checks are green.  Every public test must
    belong to exactly one phase.
    """
    raw = manifest.get("phases")
    if not isinstance(raw, list) or len(raw) < 2:
        raise ProtocolError(f"{task_id} staged manifest needs >=2 ordered phases")
    tests = {item["path"]: item for item in _public_tests(manifest)}
    claimed: set[str] = set()
    phases: list[dict[str, Any]] = []
    for index, item in enumerate(raw, start=1):
        if not isinstance(item, Mapping) or item.get("phase") != index:
            raise ProtocolError(f"{task_id} phases must be numbered 1..n in order")
        brief_name = _safe_relative(item.get("brief"), field="phase brief")
        brief_path = task_dir / brief_name
        if brief_path.is_symlink() or not brief_path.is_file():
            raise ProtocolError(f"{task_id} phase {index} brief is missing")
        paths = item.get("public_tests")
        if not isinstance(paths, list) or not paths:
            raise ProtocolError(f"{task_id} phase {index} has no public tests")
        phase_tests = []
        for path in paths:
            path = _safe_relative(path, field="phase public test")
            if path not in tests or path in claimed:
                raise ProtocolError(f"{task_id} phase test is unknown or reused: {path}")
            claimed.add(path)
            phase_tests.append(dict(tests[path]))
        phases.append({
            "phase": index,
            "brief_path": brief_name,
            "brief_sha256": _sha256_bytes(brief_path.read_bytes()),
            "ticket": brief_path.read_text(encoding="utf-8"),
            "public_tests": phase_tests,
            "public_check_paths": [test["path"] for test in phase_tests],
        })
    if claimed != set(tests):
        raise ProtocolError(f"{task_id} has public tests outside every phase")
    return phases


def _public_row(
    *, task_id: str, manifest: Mapping[str, Any], brief: str, task_digest: str,
    entry: tuple[str, str] | None = None,
    phases: Sequence[Mapping[str, Any]] | None = None,
) -> dict[str, Any]:
    files = _public_files(manifest)
    tests = _public_tests(manifest)
    selectors = manifest.get("selectors", [item["path"] for item in tests])
    if not isinstance(selectors, list) or not selectors:
        raise ProtocolError(f"{task_id} has no public selectors")
    safe_selectors = [_safe_relative(value, field="selector") for value in selectors]
    if not set(safe_selectors).issubset({item["path"] for item in tests}):
        raise ProtocolError(f"{task_id} selector is not a public test")
    staged: list[dict[str, Any]] | None = None
    if phases is not None:
        # Only phase-1 material is visible at start; later phases ride in
        # ``staged_phases`` which the runtime releases one at a time.
        tests = [dict(test) for test in phases[0]["public_tests"]]
        safe_selectors = list(phases[0]["public_check_paths"])
        staged = [
            {"phase": phase["phase"], "ticket": phase["ticket"],
             "public_tests": [dict(test) for test in phase["public_tests"]],
             "public_check_paths": list(phase["public_check_paths"])}
            for phase in phases[1:]
        ]

    entry_path, entry_fn = entry if entry is not None else ENTRYPOINTS[task_id]
    if entry_path not in files:
        raise ProtocolError(f"{task_id} entry path is not public: {entry_path}")
    row = {
        "task_id": task_id,
        "repo": "build",
        "sha": task_digest,
        "fn": entry_fn,
        "rel": entry_path,
        "path": entry_path,
        "msg": brief,
        "shape": "multi_file",
        "tier": manifest.get("rung", "LONG-HORIZON-1"),
        "files": files,
        "public_tests": tests,
        "public_check_paths": safe_selectors,
        "test_path": tests[0]["path"],
        "test_src": tests[0]["source"],
        "entry": {"path": entry_path, "fn": entry_fn},
        "changed_functions": {entry_path: [entry_fn]},
        "allowed_product_paths": list(manifest.get("allowed_product_paths", ["app"])),
    }
    if staged is not None:
        row["staged_phases"] = staged
    return row


def _staged_task_ids(family_dir: Path) -> tuple[str, ...]:
    ids = tuple(sorted(
        child.name for child in family_dir.iterdir()
        if child.is_dir() and not child.is_symlink() and _STAGED_ID_RE.match(child.name)
    ))
    if len(ids) != STAGED_TASK_COUNT:
        raise ProtocolError(
            f"{STAGED_FAMILY} must contain exactly {STAGED_TASK_COUNT} tasks, found {len(ids)}")
    if len({task_slug(task_id) for task_id in ids}) != len(ids):
        raise ProtocolError("staged task ordinals are not unique")
    return ids


def family_task_ids(task_root: str | Path, family: str) -> tuple[str, ...]:
    if family == TASK_FAMILY:
        return REQUIRED_TASK_IDS
    if family == STAGED_FAMILY:
        return _staged_task_ids(_family_dir(Path(task_root), family))
    raise ProtocolError(f"unknown task family: {family}")


def _staged_digest(manifest_path: Path, brief_path: Path,
                   phases: Sequence[Mapping[str, Any]]) -> str:
    """Task digest also covers every later-phase ticket."""
    payload = manifest_path.read_bytes() + b"\x00long-horizon-brief\x00" + brief_path.read_bytes()
    for phase in phases:
        payload += b"\x00phase\x00" + str(phase["phase"]).encode() + b"\x00" + phase["ticket"].encode()
    return _sha256_bytes(payload)


