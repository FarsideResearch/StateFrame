# ============================================================ canonical bytes
def canonical_json(obj) -> bytes:
    """UTF-8 canonical JSON: sorted keys, no insignificant whitespace.

    Contract section 8. Lists retain order; bytes must already have been
    converted to a tagged base64 form by the caller.
    """
    return json.dumps(obj, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False).encode("utf-8")


def sha256_bytes(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def sha256_json(obj) -> str:
    return sha256_bytes(canonical_json(obj))


def tagged_bytes(data: bytes) -> dict:
    return {"kind": "bytes", "encoding": "base64",
            "value": base64.b64encode(data).decode("ascii")}


