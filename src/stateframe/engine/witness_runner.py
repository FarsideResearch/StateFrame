# ==================================================================== the runner
class LocalWitnessRunner:
    """The one execution contract. `run` performs EXACTLY one attempt.

    It never raises for an expected execution failure and never retries. Every
    call produces a fresh overlay and a fresh process group; the only thing that
    may be reused between calls is the immutable prepared base.
    """

    def __init__(self, store: ContentStore, python_executable: str = None,
                 workdir: str = None):
        self.store = store
        from kernel_test_python import test_python
        self.python = python_executable or test_python()
        self._workdir = workdir
        self._prepared = {}          # base key -> verified manifest digest

    # ------------------------------------------------------------- preparation
    def base_key(self, executable: FrozenExecutable) -> str:
        return sha256_json({"witness": executable.witness_digest,
                            "runtime": executable.runtime_image_digest,
                            "deps": executable.dependency_lock_digest,
                            "policy": executable.sandbox_policy_digest})

    def prepare(self, executable: FrozenExecutable) -> str:
        """Verify every artifact digest. Never mutates, never executes target code."""
        key = self.base_key(executable)
        if key in self._prepared:
            return key
        for artifact in executable.artifact_manifest:
            data = self.store.get(artifact.content_ref)
            if data is None:
                raise PlanRejected("missing immutable artifact %s (%s)"
                                   % (artifact.path, artifact.content_digest))
            if sha256_bytes(data) != artifact.content_digest:
                raise PlanRejected("artifact digest mismatch for %s" % artifact.path)
        self._prepared[key] = executable.manifest_digest()
        return key

    # -------------------------------------------------------------------- run
    def run(self, executable: FrozenExecutable, probes: InstrumentationPlan,
            budgets: RunBudgets) -> RunResult:
        run_id = "run-" + uuid.uuid4().hex[:16]
        overlay = None
        diagnostics = {}
        try:
            # ---- 1/2/3 validation -------------------------------------------
            try:
                self.prepare(executable)
                self._validate_plan(executable, probes)
            except PlanRejected as exc:
                return self._reject(run_id, executable, probes, budgets,
                                    exc.reason)

            # ---- 4 fresh overlay --------------------------------------------
            overlay = tempfile.mkdtemp(prefix="witness-", dir=self._workdir)
            try:
                self._materialise(executable, probes, budgets, overlay)
            except PlanRejected as exc:
                return self._reject(run_id, executable, probes, budgets,
                                    exc.reason, phase="instrumentation")

            # ---- 6/7 launch + hard budget -----------------------------------
            started = time.monotonic()
            timeout_s = max(0.001, budgets.wall_clock_ms / 1000.0)
            env = self._child_env(executable, overlay)
            killed = False
            try:
                from kernel_execution_policy import ExecutionPolicyError, run_sandboxed
                execution = run_sandboxed(
                    [self.python, "-I", "-S", "-B",
                     os.path.join(overlay, CHILD_FILE)],
                    overlay,
                    env=env,
                    input_data=executable.stdin,
                    timeout=timeout_s,
                    output_limit=max(budgets.stdout_bytes, budgets.stderr_bytes),
                    cpu_seconds=min(900.0, max(1.0, (budgets.cpu_ms or budgets.wall_clock_ms) / 1000.0)),
                    memory_bytes=budgets.memory_bytes or 512 * 1024 * 1024,
                    file_bytes=max(1024 * 1024, budgets.observation_bytes),
                )
            except (OSError, ExecutionPolicyError) as exc:  # pragma: no cover
                return self._infra_failure(run_id, executable, probes, budgets,
                                           "startup", str(exc))
            proc = execution.completed
            killed = execution.timed_out
            out = (proc.stdout or "").encode("utf-8", errors="replace")
            err = (proc.stderr or "").encode("utf-8", errors="replace")
            elapsed_ms = int((time.monotonic() - started) * 1000)
            diagnostics["elapsed_ms"] = elapsed_ms
            diagnostics["sandbox"] = execution.capabilities.as_dict()
            diagnostics["output_truncated"] = execution.output_truncated

            # ---- 8 collect ---------------------------------------------------
            observations = self._read_observations(overlay, executable, probes)
            child = self._read_outcome(overlay)
            diagnostics["stdout_tail"] = out[-2048:].decode("utf-8", "replace")
            diagnostics["stderr_tail"] = err[-2048:].decode("utf-8", "replace")
            if child:
                diagnostics["limits_unenforced"] = child.get("limits_unenforced", [])

            outcome = self._classify(proc, child, killed, out, err, budgets,
                                     probes)
            return self._result(run_id, executable, probes, budgets,
                                observations, outcome, diagnostics)
        finally:
            # ---- 9/10 teardown ----------------------------------------------
            if overlay and os.path.isdir(overlay):
                shutil.rmtree(overlay, ignore_errors=True)

    # --------------------------------------------------------------- internals
    def _validate_plan(self, executable, plan):
        if plan.schema_version != SCHEMA_INSTRUMENTATION:
            raise PlanRejected("unknown instrumentation schema %r"
                               % plan.schema_version)
        if plan.plan_digest != sha256_json(plan.as_canonical()):
            raise PlanRejected("instrumentation plan digest mismatch")
        if plan.failure_policy != "halt":
            raise PlanRejected("unsupported failure policy %r" % plan.failure_policy)
        by_path = {a.path: a for a in executable.artifact_manifest}
        seen = set()
        for probe in plan.probes:
            if probe.probe_id in seen:
                raise PlanRejected("duplicate probe id %r" % probe.probe_id)
            seen.add(probe.probe_id)
            if probe.backend not in (BACKEND_AST, BACKEND_TRACE):
                raise PlanRejected("unknown backend %r" % probe.backend)
            if probe.event not in EVENTS:
                raise PlanRejected("unknown event %r" % probe.event)
            artifact = by_path.get(probe.target.file_path)
            if artifact is None:
                raise PlanRejected("probe %s targets %s which is not in the manifest"
                                   % (probe.probe_id, probe.target.file_path))
            if artifact.content_digest != probe.target.file_digest:
                raise PlanRejected("probe %s file digest mismatch for %s"
                                   % (probe.probe_id, probe.target.file_path))
            if probe.backend == BACKEND_TRACE:
                if probe.target.file_path != executable.entrypoint:
                    raise PlanRejected(
                        "probe %s: the settrace backend only observes the entrypoint"
                        % probe.probe_id)
                if probe.event == "line_exit":
                    # A line trace event is the state BEFORE the line runs; a
                    # tracer can never honestly report a post-assignment value.
                    raise PlanRejected(
                        "probe %s: sys_settrace cannot observe line_exit"
                        % probe.probe_id)

    def _materialise(self, executable, plan, budgets, overlay):
        ast_probes = {}
        trace_specs = []
        for probe in plan.probes:
            if probe.backend == BACKEND_AST:
                ast_probes.setdefault(probe.target.file_path, []).append(probe)
            else:
                trace_specs.append({"probe_id": probe.probe_id,
                                    "line": probe.target.line,
                                    "event": probe.event})
        for artifact in executable.artifact_manifest:
            data = self.store.get(artifact.content_ref)
            if data is None or sha256_bytes(data) != artifact.content_digest:
                raise PlanRejected("artifact vanished during materialisation: %s"
                                   % artifact.path)
            probes_here = ast_probes.get(artifact.path)
            if probes_here:
                data = instrument_source(data, probes_here)
            dest = os.path.join(overlay, artifact.path)
            os.makedirs(os.path.dirname(dest) or overlay, exist_ok=True)
            with open(dest, "wb") as fh:
                fh.write(data)
            os.chmod(dest, artifact.mode)

        control = {
            "entrypoint": executable.entrypoint,
            "argv": list(executable.argv),
            "budgets": budgets.as_canonical(),
            "trace_probes": trace_specs,
            "probe_config": {
                "serialization": plan.serialization.as_canonical(),
                "max_events": budgets.observation_events,
                "max_bytes": budgets.observation_bytes,
                "max_hits": {p.probe_id: p.max_hits for p in plan.probes},
                "captures": {p.probe_id: [c.as_canonical() for c in p.captures]
                             for p in plan.probes},
            },
        }
        with open(os.path.join(overlay, CONTROL_FILE), "w", encoding="utf-8") as fh:
            json.dump(control, fh, sort_keys=True)
        with open(os.path.join(overlay, PROBE_RUNTIME_FILE), "w",
                  encoding="utf-8") as fh:
            fh.write(PROBE_RUNTIME_SOURCE)
        with open(os.path.join(overlay, CHILD_FILE), "w", encoding="utf-8") as fh:
            fh.write(CHILD_SOURCE)

    def _child_env(self, executable, overlay):
        env = {}
        for name in BASE_ENV_ALLOWLIST:
            if name in os.environ:
                env[name] = os.environ[name]
        env.update({k: str(v) for k, v in executable.environment.items()})
        env["TMPDIR"] = overlay
        env["WITNESS_NETWORK_POLICY"] = executable.network_policy
        if executable.deterministic_seed is not None:
            env["PYTHONHASHSEED"] = str(executable.deterministic_seed)
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        return env

    def _read_observations(self, overlay, executable, plan):
        path = os.path.join(overlay, OBSERVATION_FILE)
        if not os.path.exists(path):
            return ()
        digest_by_probe = {p.probe_id: (p.target.file_path, p.target.file_digest)
                           for p in plan.probes}
        out = []
        with open(path, encoding="utf-8") as fh:
            for raw in fh:
                raw = raw.strip()
                if not raw:
                    continue
                try:
                    rec = json.loads(raw)
                except ValueError:                        # truncated final line
                    continue
                fpath, fdigest = digest_by_probe.get(rec.get("probe_id"),
                                                     (executable.entrypoint, ""))
                out.append(Observation(
                    sequence=rec["sequence"], monotonic_ns=rec.get("monotonic_ns", 0),
                    probe_id=rec["probe_id"], event=rec["event"],
                    file_path=fpath, file_digest=fdigest,
                    function_qualname=rec.get("function_qualname"),
                    line=rec.get("line", 0), column=rec.get("column"),
                    hit_number=rec.get("hit_number", 1),
                    values={k: Snapshot(v) for k, v in (rec.get("values") or {}).items()},
                    truncated=bool(rec.get("truncated"))))
        out.sort(key=lambda o: o.sequence)
        return tuple(out)

    @staticmethod
    def _read_outcome(overlay):
        path = os.path.join(overlay, OUTCOME_FILE)
        if not os.path.exists(path):
            return None
        try:
            with open(path, encoding="utf-8") as fh:
                return json.load(fh)
        except ValueError:                                # pragma: no cover
            return None

    def _classify(self, proc, child, killed, out, err, budgets, plan):
        """Terminal precedence, contract section 5.

        1. budget_halted wins whenever the supervisor terminated the run.
        2. probe_crashed wins when probe infrastructure initiated termination.
        3. probed_code_crashed when the target died with probes healthy.
        4. a probe failure DURING the target's exception flush is a secondary
           event, and the primary stays probed_code_crashed.
        """
        probe_requested = bool(plan.probes)
        secondary = []
        if child:
            for ev in child.get("secondary", ()):
                secondary.append(TerminalEvent(kind=ev.get("kind", "unknown"),
                                               phase=ev.get("phase", "teardown"),
                                               detail=ev.get("detail", "")))
        overflow = (child or {}).get("overflow")
        probe_status = "not_requested"
        if probe_requested:
            probe_status = "crashed" if (child or {}).get("probe_crashed") else "healthy"

        if killed:
            return OutcomeSignature(
                classification=BUDGET_HALTED, terminal_phase="execution",
                exit_code=None,
                signal="SIGKILL", budget_reason="wall_clock",
                probe_status=probe_status, secondary_events=tuple(secondary))
        if len(out) > budgets.stdout_bytes:
            return OutcomeSignature(classification=BUDGET_HALTED,
                                    terminal_phase="execution",
                                    budget_reason="stdout",
                                    probe_status=probe_status,
                                    secondary_events=tuple(secondary))
        if len(err) > budgets.stderr_bytes:
            return OutcomeSignature(classification=BUDGET_HALTED,
                                    terminal_phase="execution",
                                    budget_reason="stderr",
                                    probe_status=probe_status,
                                    secondary_events=tuple(secondary))
        if overflow:
            return OutcomeSignature(classification=BUDGET_HALTED,
                                    terminal_phase="observation_flush",
                                    budget_reason=overflow,
                                    probe_status=probe_status,
                                    secondary_events=tuple(secondary))
        if child is None:
            # The child never wrote an outcome: the interpreter died before the
            # harness could report. That is runner infrastructure, not a target
            # result, and must never be scored.
            sig = "SIG%d" % (-proc.returncode) if proc.returncode and \
                proc.returncode < 0 else None
            return OutcomeSignature(classification=RUNNER_FAILED,
                                    terminal_phase="startup",
                                    exit_code=proc.returncode, signal=sig,
                                    probe_status=probe_status,
                                    secondary_events=tuple(secondary))
        exc = None
        raw = child.get("exception")
        if raw:
            exc = ExceptionSignature(
                qualified_type=raw.get("qualified_type", "?"),
                is_base_exception=bool(raw.get("is_base_exception")),
                source_file_digest=None,
                function_qualname=raw.get("function_qualname"),
                line=raw.get("line"), column=None,
                message_digest=sha256_bytes((raw.get("message") or "").encode()))
        classification = child.get("classification", RETURNED)
        return OutcomeSignature(
            classification=classification,
            terminal_phase=child.get("terminal_phase", "execution"),
            exception=exc, exit_code=proc.returncode, signal=None,
            budget_reason=None, probe_status=probe_status,
            secondary_events=tuple(secondary))

    def _result(self, run_id, executable, plan, budgets, observations, outcome,
                diagnostics):
        obs_digest = sha256_json([o.as_semantic() for o in observations])
        receipt = self._receipt(run_id, executable, plan, budgets, obs_digest,
                                outcome, diagnostics)
        return RunResult(run_id=run_id, runner_version=RUNNER_VERSION,
                         observations=tuple(observations), outcome=outcome,
                         receipt=receipt)

    def _receipt(self, run_id, executable, plan, budgets, obs_digest, outcome,
                 diagnostics):
        body = {
            "witness_digest": executable.witness_digest,
            "fixture_digest": executable.fixture_digest,
            "executable_manifest_digest": executable.manifest_digest(),
            "instrumentation_plan_digest": plan.plan_digest,
            "budgets_digest": budgets.digest(),
            "runtime_image_digest": executable.runtime_image_digest,
            "dependency_lock_digest": executable.dependency_lock_digest,
            "sandbox_policy_digest": executable.sandbox_policy_digest,
            "runner_version": RUNNER_VERSION,
            "observations_digest": obs_digest,
            "outcome": outcome.as_canonical(),
        }
        return RunReceipt(receipt_digest=sha256_json(body), run_id=run_id,
                          outcome=outcome, observations_digest=obs_digest,
                          runner_version=RUNNER_VERSION,
                          diagnostics=dict(diagnostics),
                          **{k: v for k, v in body.items()
                             if k not in ("outcome", "observations_digest",
                                          "runner_version")})

    def _reject(self, run_id, executable, plan, budgets, reason,
                phase="validation"):
        # A rejected plan never launched the target, so probes were never
        # installed: their status is "not_requested" regardless of the plan.
        outcome = OutcomeSignature(classification=RUNNER_REJECTED,
                                   terminal_phase=phase,
                                   probe_status="not_requested")
        return self._result(run_id, executable, plan, budgets, (), outcome,
                            {"rejection_reason": reason})

    def _infra_failure(self, run_id, executable, plan, budgets, phase, detail):
        outcome = OutcomeSignature(classification=RUNNER_FAILED,
                                   terminal_phase=phase)
        return self._result(run_id, executable, plan, budgets, (), outcome,
                            {"runner_failure": detail})


# ============================================================ replay verification
def replay(runner: LocalWitnessRunner, receipt: RunReceipt,
           executable: FrozenExecutable, plan: InstrumentationPlan,
           budgets: RunBudgets) -> RunResult:
    """Re-execute the exact run a receipt cites.

    The witness/plan/budget digests must match the receipt EXACTLY. There is no
    "closest available" content: a mismatch is `runner_rejected` before anything
    executes (contract section 8).
    """
    if executable.witness_digest != receipt.witness_digest:
        return runner._reject("run-replay", executable, plan, budgets,
                              "replay witness digest mismatch")
    if plan.plan_digest != receipt.instrumentation_plan_digest:
        return runner._reject("run-replay", executable, plan, budgets,
                              "replay instrumentation plan digest mismatch")
    if budgets.digest() != receipt.budgets_digest:
        return runner._reject("run-replay", executable, plan, budgets,
                              "replay budgets digest mismatch")
    return runner.run(executable, plan, budgets)


def outcomes_equivalent(a: OutcomeSignature, b: OutcomeSignature) -> bool:
    """Semantic outcome equality, used by PROBE-LOOP to detect instrumentation
    that changed the witness. Timestamps, run ids, and exit codes carrying
    platform noise are excluded; the exception identity is not."""
    if a.classification != b.classification:
        return False
    if (a.exception is None) != (b.exception is None):
        return False
    if a.exception is not None:
        if a.exception.qualified_type != b.exception.qualified_type:
            return False
        if a.exception.is_base_exception != b.exception.is_base_exception:
            return False
        if a.exception.message_digest != b.exception.message_digest:
            return False
    return a.budget_reason == b.budget_reason
