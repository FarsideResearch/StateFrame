"""WITNESS RUNNER — the signed execution boundary shared by REPRO-SYNTH and PROBE-LOOP.

This is an implementation of the ratified contract in `/tmp/solq/w64/a_witness_seam.md`
(WitnessRunner Interface Contract v1.0.0). Both consumers execute THROUGH this
module and neither defines a competing runner protocol.

WHAT IS ACTUALLY ENFORCED (measured, not asserted)
--------------------------------------------------
Every run is a fresh OS subprocess in its own process group, launched against a
fresh writable overlay directory materialised from content-addressed artifacts.
The parent supervises a monotonic wall-clock deadline and kills the whole process
group on expiry. That gives real `budget_halted`, real `probed_code_crashed` for
`BaseException` (including `KeyboardInterrupt`/`SystemExit`, which an in-process
runner cannot survive), and real "no shared state between repro-run and probe-run"
— separate processes cannot share file descriptors, generated bytecode, random
state, or probe buffers.

WHAT IS DECLARED BUT NOT PART OF THE WITNESS RECEIPT (stated loudly)
---------------------------------------------------------------------
- `runtime_image_digest` / `dependency_lock_digest` / `sandbox_policy_digest` are
  caller-supplied identity, verified for CONSISTENCY across replay, not built
  from a container image.
- The child filesystem, network, environment, process, CPU, memory, file, and
  output boundary is enforced by `kernel_execution_policy`; receipt identity
  fields do not replace that host capability check.

Everything the contract calls a semantic guarantee — digest verification, exact
probe anchoring with no fuzzy relocation, terminal-classification precedence,
one-run-one-attempt, replayable receipts — IS enforced here and tested.

CONTAINMENT PROVENANCE — stated precisely, because the difference matters
-------------------------------------------------------------------------
`test_gen_oracle._tracer` is the in-process containment hardened after the E94
12.9 GB SIGKILL: a `_HardHalt(BaseException)` that candidate code cannot swallow,
a per-call wall-clock deadline, and growth-delta memory sampling on a CLOCK
rather than an event count. This module does NOT import it, and that is a
deliberate choice rather than drift: every one of those mechanisms exists to
approximate, from inside the interpreter, what a supervised subprocess gets for
free. Here the deadline is an `os.killpg(SIGKILL)` from the parent, so it cannot
be caught, disabled by a tracer-raised exception, or ratcheted by a high-water
RSS baseline — the three holes that measurement found in the in-process version.

What carries over verbatim is the DISCIPLINE, and the tests below pin it:
  - a budget halt survives a bare `except BaseException` in the target;
  - a halt is ONE outcome (`budget_halted`) and is never scorable;
  - memory and CPU ceilings are applied where the platform allows and reported
    as unenforced where it does not, never silently assumed.
`test_gen_oracle` keeps its own tracer because it runs candidate functions
in-process by design; the two sandboxes are different tools, not two copies.
"""

