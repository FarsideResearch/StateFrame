# ========================================================== content addressing
class ContentStore:
    """An immutable content-addressed blob store.

    A witness cites content by DIGEST, never by path (contract invariant 4).
    A missing or altered blob at replay time is a hard `runner_rejected`; there
    is deliberately no "closest available" fallback.
    """

    def __init__(self):
        self._blobs = {}

    def put(self, data: bytes) -> ImmutableContentRef:
        if isinstance(data, str):
            data = data.encode("utf-8")
        digest = sha256_bytes(data)
        existing = self._blobs.get(digest)
        if existing is not None and existing != data:      # pragma: no cover
            raise RuntimeError("sha256 collision in content store")
        self._blobs[digest] = data
        return ImmutableContentRef(digest=digest)

    def get(self, ref: ImmutableContentRef) -> Optional[bytes]:
        return self._blobs.get(ref.digest)

    def has(self, ref: ImmutableContentRef) -> bool:
        return ref.digest in self._blobs

    def evict(self, ref: ImmutableContentRef) -> None:
        """Only for proving that replay REJECTS rather than substitutes."""
        self._blobs.pop(ref.digest, None)

    def corrupt(self, ref: ImmutableContentRef, data: bytes) -> None:
        """Only for proving digest verification actually verifies."""
        self._blobs[ref.digest] = data


def freeze_executable(store: ContentStore, files: Mapping, entrypoint: str,
                      *, fixture_digest: str, argv=(), stdin: bytes = b"",
                      environment: Mapping = None,
                      runtime_image_digest: str = None,
                      dependency_lock_digest: str = "sha256:none",
                      sandbox_policy_digest: str = None,
                      deterministic_seed: Optional[int] = 0,
                      network_policy: str = "disabled",
                      modes: Mapping = None) -> FrozenExecutable:
    """Content-address every input and compute the witness digest.

    `files` maps overlay-relative path -> source text/bytes. The entrypoint must
    be one of them. Every byte that can change behaviour is folded into
    `witness_digest`: paths, exact bytes, modes, entrypoint, argv, stdin, the
    allowlisted environment, the runtime/dependency/policy identities, the seed,
    and the network policy.
    """
    modes = modes or {}
    environment = dict(environment or {})
    if runtime_image_digest is None:
        runtime_image_digest = sha256_bytes(
            ("python-" + ".".join(str(x) for x in sys.version_info[:3])).encode())
    if sandbox_policy_digest is None:
        sandbox_policy_digest = sha256_json(
            {"profile": "subprocess-overlay/v1", "network": network_policy})

    artifacts = []
    for path in sorted(files):
        if path in RESERVED_NAMES:
            raise ValueError("reserved overlay filename: %s" % path)
        data = files[path]
        if isinstance(data, str):
            data = data.encode("utf-8")
        ref = store.put(data)
        artifacts.append(Artifact(path=path, content_digest=ref.digest,
                                  mode=modes.get(path, 0o644), content_ref=ref))
    if entrypoint not in files:
        raise ValueError("entrypoint %r is not in the artifact manifest" % entrypoint)

    body = {
        "artifacts": [a.as_canonical() for a in artifacts],
        "entrypoint": entrypoint,
        "argv": list(argv),
        "stdin": tagged_bytes(stdin),
        "environment": dict(sorted(environment.items())),
        "runtime_image_digest": runtime_image_digest,
        "dependency_lock_digest": dependency_lock_digest,
        "sandbox_policy_digest": sandbox_policy_digest,
        "deterministic_seed": deterministic_seed,
        "network_policy": network_policy,
    }
    return FrozenExecutable(
        witness_digest=sha256_json(body),
        fixture_digest=fixture_digest,
        artifact_manifest=tuple(artifacts),
        entrypoint=entrypoint,
        argv=tuple(argv),
        stdin=stdin,
        environment=dict(sorted(environment.items())),
        runtime_image_digest=runtime_image_digest,
        dependency_lock_digest=dependency_lock_digest,
        sandbox_policy_digest=sandbox_policy_digest,
        deterministic_seed=deterministic_seed,
        network_policy=network_policy,
    )


# ============================================================== plan validation
class PlanRejected(Exception):
    """Validation failure. Always becomes `runner_rejected`, never an exception
    that escapes `run` (contract: run never raises for expected failures)."""

    def __init__(self, reason: str):
        super().__init__(reason)
        self.reason = reason


def ast_fingerprint(node) -> str:
    """Structural identity of one AST node, ignoring positions.

    Positions move when an unrelated line above is edited; structure does not.
    A fingerprint mismatch is therefore a real "this is no longer the statement
    you anchored to", not line drift.
    """
    return sha256_bytes(ast.dump(node, annotate_fields=True,
                                 include_attributes=False).encode("utf-8"))


def _statement_index(source: bytes):
    """(line, col) -> [statement nodes]. Only statements can carry a probe."""
    tree = ast.parse(source.decode("utf-8"))
    index = {}
    for parent in ast.walk(tree):
        for fieldname in ("body", "orelse", "finalbody"):
            body = getattr(parent, fieldname, None)
            if not isinstance(body, list):
                continue
            for pos, node in enumerate(body):
                if not isinstance(node, ast.stmt):
                    continue
                index.setdefault((node.lineno, node.col_offset), []).append(
                    (parent, fieldname, pos, node))
    return tree, index


def _enclosing_qualname(tree, target_node):
    """The dotted qualname of the function/class containing `target_node`."""
    result = [None]

    def walk(node, prefix):
        for child in ast.iter_child_nodes(node):
            if isinstance(child, (ast.FunctionDef, ast.AsyncFunctionDef,
                                  ast.ClassDef)):
                name = prefix + child.name
                if child is target_node:
                    result[0] = name
                    return True
                if walk(child, name + "."):
                    if result[0] is None:
                        result[0] = name
                    return True
            else:
                if child is target_node:
                    result[0] = prefix[:-1] if prefix else None
                    return True
                if walk(child, prefix):
                    return True
        return False

    walk(tree, "")
    return result[0]


# ================================================================ AST rewriting
#: Compound statements cannot be probed by source splicing: `emit(); if x:` is
#: a syntax error, and an after-probe spliced onto a compound header would fire
#: before the block, not after it. Such a site is REJECTED rather than moved.
_COMPOUND = (ast.If, ast.For, ast.AsyncFor, ast.While, ast.With, ast.AsyncWith,
             ast.Try, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)
if hasattr(ast, "Match"):                                   # pragma: no branch
    _COMPOUND = _COMPOUND + (ast.Match,)
if hasattr(ast, "TryStar"):                                 # pragma: no cover
    _COMPOUND = _COMPOUND + (ast.TryStar,)


def _emit_text(probe_id, event, line, col, qualname):
    """The one-line emit call, as SOURCE TEXT.

    Injection is textual rather than AST-then-`ast.unparse` for one measured
    reason: `unparse` regenerates the whole file, which SHIFTS every line below
    an inserted statement. The instrumented run then reports its exception one
    line off the uninstrumented one — a probe that silently changes the evidence
    it was installed to collect. Splicing into the existing line keeps every
    original line number byte-exact, which is what the design requires.
    """
    return ("__witness_emit__(%r, %r, %r, %r, %r, locals())"
            % (probe_id, event, line, col, qualname))


def instrument_source(source: bytes, probes) -> bytes:
    """Apply every AST-backend probe to one file's source, preserving lines.

    Raises `PlanRejected` when a probe cannot be placed EXACTLY. There is no
    fuzzy relocation and no nearest-line fallback (contract invariant 3).
    """
    if not probes:
        return source
    tree, index = _statement_index(source)
    lines = source.decode("utf-8").splitlines(keepends=True)
    # (line index) -> [(column, ordering, text_before, text_after)]
    splices = {}
    for probe in probes:
        key = (probe.target.line, probe.target.column)
        if probe.target.column is None:
            matches = [v for (ln, _c), vs in index.items() if ln == probe.target.line
                       for v in vs]
        else:
            matches = list(index.get(key, ()))
        if not matches:
            raise PlanRejected("probe %s resolved zero statements at %s:%s"
                               % (probe.probe_id, probe.target.file_path,
                                  probe.target.line))
        if len(matches) > 1:
            raise PlanRejected("probe %s resolved %d statements at %s:%s"
                               % (probe.probe_id, len(matches),
                                  probe.target.file_path, probe.target.line))
        _parent, _fieldname, _pos, node = matches[0]
        if probe.target.ast_fingerprint and \
                ast_fingerprint(node) != probe.target.ast_fingerprint:
            raise PlanRejected("probe %s ast fingerprint mismatch at %s:%s"
                               % (probe.probe_id, probe.target.file_path,
                                  probe.target.line))
        if isinstance(node, _COMPOUND):
            raise PlanRejected(
                "probe %s: a compound statement cannot be instrumented safely "
                "at %s:%s" % (probe.probe_id, probe.target.file_path,
                              probe.target.line))
        qual = probe.target.function_qualname or _enclosing_qualname(tree, node)
        row = node.lineno - 1

        if probe.event == "return":
            if not isinstance(node, ast.Return) or node.value is None:
                raise PlanRejected(
                    "probe %s requests a return probe on a non-value return at %s:%s"
                    % (probe.probe_id, probe.target.file_path, probe.target.line))
            value = node.value
            if value.lineno != value.end_lineno:
                raise PlanRejected(
                    "probe %s: a multi-line return expression cannot be wrapped "
                    "in place at %s:%s" % (probe.probe_id,
                                           probe.target.file_path,
                                           probe.target.line))
            prefix = ("__witness_return__(%r, %r, %r, %r, "
                      % (probe.probe_id, node.lineno, node.col_offset, qual))
            splices.setdefault(row, []).append(
                (value.col_offset, 0, prefix, ""))
            splices.setdefault(row, []).append(
                (value.end_col_offset, 1, "", ")"))
            continue

        if probe.event not in ("line_entry", "line_exit"):
            raise PlanRejected(
                "probe %s: backend %s cannot instrument event %r"
                % (probe.probe_id, BACKEND_AST, probe.event))
        if probe.event == "line_entry":
            splices.setdefault(row, []).append(
                (node.col_offset, 0,
                 _emit_text(probe.probe_id, "line_entry", node.lineno,
                            node.col_offset, qual) + "; ", ""))
            continue

        # line_exit
        if isinstance(node, (ast.Return, ast.Raise, ast.Break, ast.Continue)):
            # A statement that leaves the block can never be followed by an
            # after-probe. probe_loop section 4 names this exact case.
            raise PlanRejected(
                "probe %s: line_exit is unreachable after a control-flow exit at %s:%s"
                % (probe.probe_id, probe.target.file_path, probe.target.line))
        if node.lineno != node.end_lineno:
            raise PlanRejected(
                "probe %s: line_exit on a multi-line statement cannot preserve "
                "line numbers at %s:%s" % (probe.probe_id,
                                           probe.target.file_path,
                                           probe.target.line))
        splices.setdefault(row, []).append(
            (node.end_col_offset, 2,
             "; " + _emit_text(probe.probe_id, "line_exit", node.lineno,
                               node.col_offset, qual), ""))

    for row, items in splices.items():
        if row >= len(lines):                                # pragma: no cover
            raise PlanRejected("probe target line %d is past end of file" % (row + 1))
        text = lines[row]
        # Apply from the RIGHT so earlier column offsets stay valid.
        for column, _order, before, after in sorted(items, key=lambda t: (-t[0],
                                                                          -t[1])):
            text = text[:column] + before + after + text[column:]
        lines[row] = text
    return "".join(lines).encode("utf-8")


