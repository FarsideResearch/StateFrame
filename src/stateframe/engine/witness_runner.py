def instrumentation_plan(probes=(), serialization=None,
                         failure_policy="halt") -> InstrumentationPlan:
    """Build a plan with its digest computed over its own canonical form."""
    serialization = serialization or SerializationPolicy()
    body = {"schema_version": SCHEMA_INSTRUMENTATION,
            "probes": [p.as_canonical() for p in probes],
            "serialization": serialization.as_canonical(),
            "failure_policy": failure_policy}
    return InstrumentationPlan(schema_version=SCHEMA_INSTRUMENTATION,
                               plan_digest=sha256_json(body),
                               probes=tuple(probes),
                               serialization=serialization,
                               failure_policy=failure_policy)


