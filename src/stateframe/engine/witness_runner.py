PROBE_RUNTIME_SOURCE = r'''
"""In-child probe runtime. Bounded, side-effect free, no ``repr`` calls."""
import json, os, sys, time

_STATE = {"seq": 0, "events": 0, "bytes": 0, "overflow": None,
          "crashed": False, "hits": {}}
_CFG = {}
_FH = [None]


class ProbeCrash(BaseException):
    """A probe-infrastructure failure. Derives from BaseException so target code
    cannot swallow it with ``except Exception`` and continue running with the
    observation channel already broken."""


def configure(cfg, path):
    _CFG.update(cfg)
    _FH[0] = open(path, "w", encoding="utf-8")


def state():
    return _STATE


def _policy():
    return _CFG.get("serialization", {})


def snapshot(value, depth=0):
    """Tagged rendering. NEVER calls repr, properties, or descriptors."""
    pol = _policy()
    max_depth = pol.get("max_depth", 3)
    max_items = pol.get("max_container_items", 16)
    max_str = pol.get("max_string_bytes", 4096)
    t = type(value)
    if value is None:
        return {"kind": "none"}
    if t is bool:
        return {"kind": "bool", "value": value}
    if t is int:
        return {"kind": "int", "value": value}
    if t is float:
        return {"kind": "float", "value": repr(value) if value != value or
                value in (float("inf"), float("-inf")) else value}
    if t is str:
        raw = value.encode("utf-8")
        return {"kind": "str", "length": len(value),
                "truncated": len(raw) > max_str,
                "value": raw[:max_str].decode("utf-8", "replace")}
    if t in (bytes, bytearray):
        import base64
        raw = bytes(value)
        return {"kind": "bytes", "length": len(raw), "encoding": "base64",
                "truncated": len(raw) > max_str,
                "value": base64.b64encode(raw[:max_str]).decode("ascii")}
    if depth >= max_depth:
        return {"kind": "opaque", "type": _typename(t), "reason": "max-depth"}
    if t in (list, tuple, set, frozenset):
        items = list(value)[:max_items] if t in (list, tuple) else \
            sorted((_stable_key(x) for x in value))[:max_items]
        if t in (set, frozenset):
            return {"kind": t.__name__, "length": len(value),
                    "truncated": len(value) > max_items,
                    "items": [{"kind": "opaque-key", "value": k} for k in items]}
        return {"kind": t.__name__, "length": len(value),
                "truncated": len(value) > max_items,
                "items": [snapshot(x, depth + 1) for x in items]}
    if t is dict:
        keys = list(value.keys())
        try:
            keys = sorted(keys, key=_stable_key)
        except Exception:
            pass
        out = []
        for k in keys[:max_items]:
            out.append([snapshot(k, depth + 1), snapshot(value[k], depth + 1)])
        return {"kind": "dict", "length": len(value),
                "truncated": len(value) > max_items, "items": out}
    return {"kind": "opaque", "type": _typename(t)}


def _typename(t):
    mod = getattr(t, "__module__", "") or ""
    name = getattr(t, "__qualname__", None) or getattr(t, "__name__", "?")
    return (mod + "." + name) if mod and mod != "builtins" else name


def _stable_key(x):
    t = type(x)
    if t in (str, int, float, bool) or x is None:
        return (0, str(t.__name__), str(x))
    return (1, _typename(t), "")


def _write(record):
    fh = _FH[0]
    if fh is None:
        return
    line = json.dumps(record, sort_keys=True, separators=(",", ":"),
                      ensure_ascii=False)
    payload = len(line.encode("utf-8")) + 1
    if _STATE["events"] + 1 > _CFG.get("max_events", 2048):
        _STATE["overflow"] = "observation_events"
        return
    if _STATE["bytes"] + payload > _CFG.get("max_bytes", 512 * 1024):
        _STATE["overflow"] = "observation_bytes"
        return
    _STATE["events"] += 1
    _STATE["bytes"] += payload
    fh.write(line + "\n")
    fh.flush()


def _captures(probe_id):
    return _CFG.get("captures", {}).get(probe_id, [])


def _collect(probe_id, frame_locals, extra=None):
    values, truncated = {}, False
    for cap in _captures(probe_id):
        kind = cap.get("kind")
        if kind == "local":
            name = cap.get("name")
            if name in (frame_locals or {}):
                values[name] = snapshot(frame_locals[name])
            else:
                values[name] = {"kind": "unavailable", "reason": "local-not-bound"}
        elif kind == "locals":
            for name in cap.get("names") or []:
                if name in (frame_locals or {}):
                    values[name] = snapshot(frame_locals[name])
                else:
                    values[name] = {"kind": "unavailable",
                                    "reason": "local-not-bound"}
        elif kind == "frame_metadata":
            values["__frame__"] = {"kind": "frame",
                                   "locals_count": len(frame_locals or {})}
        elif kind in ("return_value", "exception"):
            if extra is not None and kind in extra:
                values[kind] = snapshot(extra[kind])
            else:
                values[kind] = {"kind": "unavailable", "reason": "not-at-this-event"}
    return values, truncated


def emit(probe_id, event, line, col, qualname, frame_locals, extra=None):
    if _STATE["crashed"] or _STATE["overflow"]:
        return
    hits = _STATE["hits"]
    hits[probe_id] = hits.get(probe_id, 0) + 1
    if hits[probe_id] > _CFG.get("max_hits", {}).get(probe_id, 32):
        return
    try:
        values, truncated = _collect(probe_id, frame_locals, extra)
    except Exception as exc:
        # An ordinary snapshot failure is UNKNOWN evidence, never a probe crash
        # and never a hypothesis contradiction (probe_loop section 5).
        values = {"__snapshot_error__": {"kind": "unavailable",
                                         "reason": type(exc).__name__}}
        truncated = False
    except BaseException:
        _STATE["crashed"] = True
        raise ProbeCrash("probe snapshot raised BaseException")
    _STATE["seq"] += 1
    _write({"schema": 1, "sequence": _STATE["seq"],
            "monotonic_ns": time.monotonic_ns(), "probe_id": probe_id,
            "event": event, "line": line, "column": col,
            "function_qualname": qualname, "hit_number": hits[probe_id],
            "values": values, "truncated": truncated})


def emit_return(probe_id, line, col, qualname, value):
    emit(probe_id, "return", line, col, qualname, {},
         extra={"return_value": value})
    return value


def close():
    if _FH[0] is not None:
        _FH[0].close()
        _FH[0] = None
'''


